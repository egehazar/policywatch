"""Writes the numbers of stale/RESULT_missing2.md from the larger missing points test's outputs (stale/PREREG_missing2.md):
missing2_measures.json (measures 1, 2, the cards and the timings), missing2_result.json (measure 3 and the readings),
missing2_gpt.json (GPT as the second rater, reported, not read; optional), and the pilot's missing_measures.json /
missing_result.json for the pooled view (descriptive only).

Everything above the marker line is regenerated; anything below it (the prose, written by hand) is kept.
Usage  py -m stale.missing2_report
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); OUT = os.path.join(HERE, 'out')
sys.path.insert(0, ROOT)
from stale.missing2 import ARMS, CARD_ARMS
from stale.missing import wilson
from stale.missing_report import MARK, KEV_PIECE, KEV_Q, INSTRUCT_Q, load, ci, pct

SHORT = {'KEV': 'KEV', 'RERANK': 'RERANK', 'BM25': 'BM25', 'CASCADE_KEV': 'CASC. KEV', 'CASCADE_QWEN': 'CASC. QWEN'}


def build(out=OUT, dest=None):
    dest = dest or os.path.join(HERE, 'RESULT_missing2.md')
    M, R, G = load('missing2_measures.json', out), load('missing2_result.json', out), load('missing2_gpt.json', out)
    PM, PR = load('missing_measures.json', out), load('missing_result.json', out)
    L = ['# Result: missing points, the larger test (10 more documents, and Kev against its base family)', '',
         'GENERATED by `py -m stale.missing2_report` from `stale/out/missing2_measures.json`, `missing2_result.json` and '
         '`missing2_gpt.json` (the pilot\'s `missing_measures.json` / `missing_result.json` for the pooled view); the prose '
         'below the marker is written by hand. Pre-registration: `stale/PREREG_missing2.md` (hashes in '
         '`stale/PREREG_missing2.sha256`).', '']
    if R:
        p = R['precision_at_10']
        L += ['## Readings (fixed in advance)',
              f'- **Replication: {R["reading_replication"]}.** Kev\'s precision@10 {p["KEV"]["yes_share"]:.3f} (needs at least '
              f'.30), Wilson lower bound {p["KEV"]["wilson95"][0]:.3f} (needs at least .15); measure 1 KEV - BM25: '
              f'{R["measures"]["KEV_minus_BM25_auroc"]["reading"]} (needs KEV better).',
              f'- **Kev against the reranker: {R["reading_reranker"]}.** Measure 1 KEV - RERANK: '
              f'{R["measures"]["KEV_minus_RERANK_auroc"]["reading"]}; precision@10 KEV {p["KEV"]["yes_share"]:.3f} vs RERANK '
              f'{p["RERANK"]["yes_share"]:.3f}.',
              f'- **Decision-model training: {R["reading_base_family"]}.** Measure 1 CASCADE_KEV - CASCADE_QWEN on the same '
              f'shortlisted passages; precision@10 CASCADE_KEV {p["CASCADE_KEV"]["yes_share"]:.3f} vs CASCADE_QWEN '
              f'{p["CASCADE_QWEN"]["yes_share"]:.3f} (reported beside it).',
              f'- Validity: {R["random_yes"]} of {R["random_n"]} random control cards rated YES (at most 3 allowed): '
              f'{"valid" if R["valid"] else "NOT VALID"}.', '']
    if M:
        L += ['## Measure 1 (primary): known positives against negatives, AUROC by case score', '',
              '| Document | positives | negatives | ' + ' | '.join(SHORT[a] for a in ARMS) + ' |', '|---|---|---|' + '---|' * len(ARMS)]
        for r in M['docs']:
            L.append(f'| {r["doc"][:-3]} | {r["positives"]} | {r["negatives"]} | ' + ' | '.join(f'{r[a + "_auroc"]:.3f}' for a in ARMS) + ' |')
        L += [f'| **Mean of the {len(M["docs"])}** | | | ' + ' | '.join(f'**{M["auroc"][a]:.3f}**' for a in ARMS) + ' |', '',
              f'- KEV - RERANK: {ci(M["KEV_minus_RERANK_auroc"])}.',
              f'- KEV - BM25: {ci(M["KEV_minus_BM25_auroc"])}.',
              f'- CASCADE_KEV - CASCADE_QWEN: {ci(M["CASCADE_KEV_minus_CASCADE_QWEN_auroc"])}.',
              '- 95% intervals from 2,000 draws resampling positives and negatives within each document (seed 20261122). '
              'The cascade arms score each case on the reranker\'s top 3 passages for it; the other arms on every passage.', '',
              '## Measure 2 (descriptive): recall@20, share of known positives in the top 20 of the asked cases', '',
              '| Document | ' + ' | '.join(SHORT[a] for a in ARMS) + ' |', '|---|' + '---|' * len(ARMS)]
        for r in M['docs']:
            L.append(f'| {r["doc"][:-3]} | ' + ' | '.join(f'{r[a + "_recall20"]:.3f}' for a in ARMS) + ' |')
        L += ['| **Mean** | ' + ' | '.join(f'**{M["recall_at_20"][a]:.3f}**' for a in ARMS) + ' |', '']
    if R:
        c = M['cards'] if M else {}; p = R['precision_at_10']; d = R['precision_diff']
        L += ['## Measure 3: new suggestions, rated blind (one Claude Opus subagent; case and passage only)', '',
              f'{c.get("total", "?")} cards: each card arm\'s top 10 negatives per document with its best passage, '
              f'deduplicated over document, case and passage, plus {c.get("random", "?")} random controls. A negative is a '
              'case with no approved point on the service. BM25 is not a card arm in this test.', '',
              '| | ' + ' | '.join(SHORT[a] for a in CARD_ARMS) + ' |', '|---|' + '---|' * len(CARD_ARMS),
              '| Precision@10: rated YES [Wilson 95%] | ' + ' | '.join(pct(p[a]) for a in CARD_ARMS) + ' |',
              '| YES or PARTLY | ' + ' | '.join(f'{p[a]["yes_or_partly_share"]:.3f}' for a in CARD_ARMS) + ' |', '',
              f'- KEV - RERANK precision: {d["KEV_minus_RERANK"]["point"]:+.3f} [{d["KEV_minus_RERANK"]["ci95"][0]:+.3f}, '
              f'{d["KEV_minus_RERANK"]["ci95"][1]:+.3f}] (descriptive).',
              f'- CASCADE_KEV - CASCADE_QWEN precision: {d["CASCADE_KEV_minus_CASCADE_QWEN"]["point"]:+.3f} '
              f'[{d["CASCADE_KEV_minus_CASCADE_QWEN"]["ci95"][0]:+.3f}, {d["CASCADE_KEV_minus_CASCADE_QWEN"]["ci95"][1]:+.3f}] '
              '(descriptive).',
              '- Intervals from 2,000 draws resampling documents (seed 20261123).', '']
    if G:
        g, cl, a = G['gpt']['precision_at_10'], G['claude']['precision_at_10'], G['agreement']
        L += ['### The same cards rated by GPT (second rater; reported, not read)', '',
              '| | ' + ' | '.join(SHORT[x] for x in CARD_ARMS) + ' | random controls YES |', '|---|' + '---|' * (len(CARD_ARMS) + 1),
              '| Claude (the rater the readings use) | ' + ' | '.join(pct(cl[x]) for x in CARD_ARMS) + f' | {G["claude"]["random_yes"]}/{G["random_n"]} |',
              '| GPT | ' + ' | '.join(pct(g[x]) for x in CARD_ARMS) + f' | {G["gpt"]["random_yes"]}/{G["random_n"]} |',
              '| Both rated YES | ' + ' | '.join(f'{a["both_yes_by_arm"][x]}/{cl[x]["cards"]}' for x in CARD_ARMS) + ' | |', '',
              f'Card-level agreement on YES vs not YES: {a["agree"]} of {a["cards"]} cards, kappa {a["kappa"]:.3f} '
              f'(Claude YES {a["claude_yes"]}, GPT YES {a["gpt_yes"]}).', '']
    if M and M.get('timing'):
        kt, rt, qt = M['timing']['KEV'] or {}, M['timing']['RERANK'] or {}, M['timing']['QWEN'] or {}
        L += ['## Measure 4: cost', '',
              'Kev-4B Q8 for the KEV arm (every passage, one request per passage with all of the document\'s questions not '
              'already cached), the reranker on every cell, and Qwen3.5-4B instruct (Kev\'s base family; llama.cpp, 6 '
              'threads, host prompt cache off) on the shortlist cells only. One model job at a time; the scanner backfill '
              'was stopped for the test. Kev\'s prediction from the cost benchmark: 7.38 s per passage + 0.931 s per question.', '',
              '| Document | passages | Kev cells asked (cached) | Kev s | predicted Kev s | reranker s | Qwen cells | Qwen s | Qwen s per cell |',
              '|---|---|---|---|---|---|---|---|---|']
        T = {'p': 0, 'a': 0, 'c': 0, 's': 0.0, 'pred': 0.0, 'r': 0.0, 'qc': 0, 'qs': 0.0}
        for doc, t in kt.items():
            q = qt.get(doc, {}); pred = t['pieces'] * KEV_PIECE + t['asked_cells'] * KEV_Q; rr = rt.get(doc, 0)
            T['p'] += t['pieces']; T['a'] += t['asked_cells']; T['c'] += t['cached_cells']; T['s'] += t['seconds']
            T['pred'] += pred; T['r'] += rr; T['qc'] += q.get('cells', 0); T['qs'] += q.get('seconds', 0)
            per = f'{q["seconds"] / q["cells"]:.2f}' if q.get('cells') else ''
            L.append(f'| {doc[:-3]} | {t["pieces"]} | {t["asked_cells"]:,} ({t["cached_cells"]}) | {t["seconds"]:,.0f} | {pred:,.0f} | '
                     f'{rr:,.0f} | {q.get("cells", 0)} | {q.get("seconds", 0):,.0f} | {per} |')
        qs = T['qs'] / T['qc'] if T['qc'] else 0; cells = T['a'] + T['c']
        L += [f'| **All {len(kt)}** | {T["p"]} | {T["a"]:,} ({T["c"]:,}) | **{T["s"]:,.0f}** ({T["s"] / 3600:.2f} h) | '
              f'{T["pred"]:,.0f} | {T["r"]:,.0f} ({T["r"] / 3600:.2f} h) | {T["qc"]:,} | **{T["qs"]:,.0f}** ({T["qs"] / 3600:.2f} h) | '
              f'**{qs:.2f}** |', '',
              f'- Kev: {T["s"] / T["a"]:.2f} s per asked cell, {T["s"] / T["pred"]:.2f}x the benchmark\'s prediction.',
              f'- Qwen3.5-4B instruct: {qs:.2f} s per cell measured here (the benchmark\'s figure was {INSTRUCT_Q} s), '
              f'{qs / (T["s"] / T["a"]):.1f}x Kev\'s per cell. At that rate the KEV arm\'s {cells:,} cells would take about '
              f'{cells * qs / 3600:.1f} h (estimated, not run); Kev took {T["s"] / 3600:.1f} h for the {T["a"]:,} not already cached.',
              f'- The reranker: {T["r"] / cells:.2f} s per cell, {T["r"] / 3600:.2f} h for every cell.', '']
    if M:
        a = M['auroc']; dd = M['KEV_minus_RERANK_auroc']; cc = M['CASCADE_KEV_minus_CASCADE_QWEN_auroc']
        L += ['## Predictions (from the pre-registration) against the result', '', '| | predicted | result |', '|---|---|---|',
              f'| AUROC KEV / RERANK / BM25 | .72-.80 / .63-.72 / .50-.58 | {a["KEV"]:.3f} / {a["RERANK"]:.3f} / {a["BM25"]:.3f} |',
              f'| AUROC CASCADE_KEV / CASCADE_QWEN | within .02 of KEV / .70-.80 | {a["CASCADE_KEV"]:.3f} / {a["CASCADE_QWEN"]:.3f} |',
              f'| KEV - RERANK (AUROC) | +.04 to +.10, P(KEV better) 60% | {dd["point"]:+.3f}, {dd["reading"]} |',
              f'| CASCADE_KEV - CASCADE_QWEN (AUROC) | about 0, P(no difference shown) 75% | {cc["point"]:+.3f}, {cc["reading"]} |']
        if R:
            p = R['precision_at_10']
            L += [f'| Precision@10 KEV / RERANK | .35-.50 / .18-.30 | {p["KEV"]["yes_share"]:.3f} / {p["RERANK"]["yes_share"]:.3f} |',
                  f'| Precision@10 CASCADE_KEV / CASCADE_QWEN | .35-.50 each | {p["CASCADE_KEV"]["yes_share"]:.3f} / {p["CASCADE_QWEN"]["yes_share"]:.3f} |',
                  f'| Replicated | P = 70% | {R["reading_replication"]} |']
        L.append('')
    if M and PM:
        n1, n2 = len(PM['docs']), len(M['docs'])
        L += [f'## Pooled with the pilot ({n1} + {n2} = {n1 + n2} documents; descriptive only)', '',
              '| | KEV | RERANK | BM25 |', '|---|---|---|---|',
              '| Mean AUROC | ' + ' | '.join(f'{(PM["auroc"][x] * n1 + M["auroc"][x] * n2) / (n1 + n2):.3f}' for x in ('KEV', 'RERANK', 'BM25')) + ' |']
        if R and PR:
            row = []
            for x in ('KEV', 'RERANK'):
                y = PR['precision_at_10'][x]['yes'] + R['precision_at_10'][x]['yes']; n = PR['precision_at_10'][x]['cards'] + R['precision_at_10'][x]['cards']
                lo, hi = wilson(y, n); row.append(f'{y}/{n} = {y / n:.3f} [{lo:.3f}, {hi:.3f}]')
            L.append('| Precision@10 rated YES [Wilson 95%] | ' + ' | '.join(row) + ' | (not a card arm here) |')
        L += ['', 'The pilot\'s cards were rated by a different Opus subagent; the two raters used the same instructions.', '']
    prose = ''
    if os.path.exists(dest):
        old = open(dest, encoding='utf-8').read()
        if MARK in old: prose = old.split(MARK, 1)[1].lstrip('\n')
    with open(dest, 'w', encoding='utf-8', newline='\n') as f: f.write('\n'.join(L) + '\n' + MARK + '\n\n' + prose)
    print(dest, len(L), 'lines generated;', 'prose kept' if prose else 'no prose yet')


if __name__ == '__main__':
    build()
