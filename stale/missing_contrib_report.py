"""Writes the numbers of stale/RESULT_missing_contrib.md (stale/PLAN_missing_contrib.md) from missing_contrib_docs.json,
the two score files' timings, missing_contrib_result.json (the Claude raters' verdicts, scored by
`py -m stale.missing_contrib score`) and, if it exists, missing_contrib_gpt.json (GPT, reported, never read).

Everything above the marker line is regenerated; anything below it (the prose, written by hand) is kept.
Usage  py -m stale.missing_contrib_report
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); OUT = os.path.join(HERE, 'out')
sys.path.insert(0, ROOT)
from stale.missing_report import MARK, load, pct as pct3
from stale import missing_contrib as X


def pct(a): return pct3(a) if a['cards'] else 'no cards'


def d3(x): return f'{x["point"]:+.3f} [{x["ci95"][0]:+.3f}, {x["ci95"][1]:+.3f}]'


def build(out=OUT, dest=None):
    dest = dest or os.path.join(HERE, 'RESULT_missing_contrib.md')
    D = load('missing_contrib_docs.json', out); R = load('missing_contrib_result.json', out); G = load('missing_contrib_gpt.json', out)
    T = {a: (load(f'missing_contrib_{a.lower()}.json', out) or {}).get('_timing', {}) for a in ('KEV', 'RERANK')}
    L = ['# Result: missing points beyond the 20 platforms, and the printed p(yes) as a label', '',
         'GENERATED by `py -m stale.missing_contrib_report` from `stale/out/missing_contrib_*.json`; the prose below the '
         'marker is written by hand. Plan: `stale/PLAN_missing_contrib.md` (hashes in `stale/PLAN_missing_contrib.sha256`). '
         'The raters are AI models, not people.', '']
    if D:
        docs = D['docs']
        L += ['## The documents',
              f'- {len(docs)} drawn from {D["population"]} (contrib at {D["archive_head"][:10]}): '
              f'{sum(d["type"] == "privacy" for d in docs)} privacy policies, {sum(d["type"] == "terms" for d in docs)} terms, '
              f'one per service; {sum(len(d["pieces"]) for d in docs):,} passages, '
              f'{sum(len(d["pieces"]) * len(d["cases"]) for d in docs):,} passage-case cells.',
              f'- Candidate cases: {sum(len(d["negatives"]) for d in docs)} document-case pairs with no approved point on '
              f'the service; {sum(len(d["excluded"]) for d in docs)} excluded because the service has one; '
              f'{sum(len(d["positives"]) for d in docs)} known positives (scored, never suggested).', '']
    if T['RERANK'] or T['KEV']:
        cells = {d['doc']: len(d['pieces']) * len(d['cases']) for d in (D or {}).get('docs', [])}
        rs = sum(T['RERANK'].values()); rc = sum(cells.get(k, 0) for k in T['RERANK'])
        ks = sum(t['seconds'] for t in T['KEV'].values()); ka = sum(t['asked_cells'] for t in T['KEV'].values())
        L += ['## Cost (this machine, 6 cores)']
        if rc: L.append(f'- Reranker on every cell: {rs:,.0f} s ({rs / 3600:.1f} h), {rs / rc:.2f} s per cell.')
        if ka: L.append(f'- Kev on the shortlist: {ka:,} cells asked, {ks:,.0f} s ({ks / 3600:.1f} h), {ks / ka:.2f} s per asked cell.')
        L.append('')
    if R:
        p, r, lab = R['precision_at_10']['PAGE'], R['precision_at_10']['RERANK'], R['label']
        L += ['## Readings (fixed in advance)',
              f'- Validity: {R["random_yes"]} of {R["random_n"]} random controls rated YES (at most {X.MAX_RANDOM_YES} '
              f'allowed): {"valid" if R["valid"] else "NOT VALID"}.',
              f'- Page precision: {pct(p)}, predicted .60-.80: **{R["reading_page"]}**.',
              f'- PAGE - RERANK: {d3(R["PAGE_minus_RERANK"])} over {R["PAGE_minus_RERANK"]["documents"]} documents, '
              f'**{R["reading_compare"]}** (predicted +.05 to +.25; P(PAGE better) was put at 65%).',
              f'- The label (PAGE cards printed at p(yes) 0.90 or more): {pct(lab["high"])} (predicted .75-.90); the rest '
              f'{pct(lab["rest"])} (predicted .30-.55); high - rest {d3(lab["high_minus_rest"])} '
              f'({lab["high_minus_rest"]["draws_used"]} of {X.DRAWS} draws used). **{R["reading_label"]}** (needs a Wilson '
              f'low of at least {X.LABEL_MIN:.2f} and high - rest above 0; P(adopted) was put at 70%).', '',
              '| | PAGE (Kev on the shortlist) | RERANK (every passage) |', '|---|---|---|',
              f'| Rated YES [Wilson 95%] | {pct(p)} | {pct(r)} |',
              f'| YES or PARTLY | {p["yes_or_partly_share"]:.3f} | {r["yes_or_partly_share"]:.3f} |', '',
              '## Descriptive (nothing is read from these)', '',
              '| Subset | PAGE YES | RERANK YES |', '|---|---|---|']
        for t, name in (('privacy', 'Privacy policies'), ('terms', 'Terms')):
            b = R['by_type'][t]; L.append(f'| {name} | {pct(b["PAGE"])} | {pct(b["RERANK"])} |')
        for g in ('1-5', '6-10'):
            L.append(f'| Ranks {g} | {pct(R["by_rank"]["PAGE"][g])} | {pct(R["by_rank"]["RERANK"][g])} |')
        for g, b in R['by_known_positives'].items():
            L.append(f'| Documents with {g} known positives | {pct(b["PAGE"])} | {pct(b["RERANK"])} |')
        for x in sorted(R['by_folder']):
            b = R['by_folder'][x]; L.append(f'| Rater {x.upper()} (folder {x}) | {pct(b["PAGE"])} | {pct(b["RERANK"])} |')
        kp = {d['doc']: len(d['positives']) for d in (D or {}).get('docs', [])}
        L += ['', f'- Verdicts on all {sum(R["verdict_counts"].values())} cards: ' +
              ', '.join(f'{k} {R["verdict_counts"].get(k, 0)}' for k in X.VERD) + '.', '',
              '| Document | Known positives | PAGE YES | RERANK YES |', '|---|---:|---:|---:|']
        for doc, b in R['by_doc'].items():
            L.append(f'| {doc[:-3]} | {kp.get(doc, "")} | {b["PAGE"]["yes"]}/{b["PAGE"]["cards"]} | {b["RERANK"]["yes"]}/{b["RERANK"]["cards"]} |')
        L.append('')
    if G:
        g, a = G['gpt'], G['agreement']
        L += ['## Second rater: GPT (reported, never read)',
              f'- GPT: PAGE {pct(g["precision_at_10"]["PAGE"])}, RERANK {pct(g["precision_at_10"]["RERANK"])}; '
              f'PAGE - RERANK {d3(g["PAGE_minus_RERANK"])}; random controls rated YES {g["random_yes"]} of {G["random_n"]}.',
              f'- GPT on the label: high {pct(g["label"]["high"])}, rest {pct(g["label"]["rest"])}, high - rest '
              f'{d3(g["label"]["high_minus_rest"])}.',
              f'- Agreement with the Claude raters on YES against not YES: {a["agree_yes_vs_not"]} of {a["cards"]} cards, '
              f'kappa {a["kappa_yes_vs_not"]}; same verdict of three on {a["agree_three_way"]}.', '']
    prose = ''
    if os.path.exists(dest):
        old = open(dest, encoding='utf-8').read()
        if MARK in old: prose = old.split(MARK, 1)[1].lstrip('\n')
    with open(dest, 'w', encoding='utf-8', newline='\n') as f: f.write('\n'.join(L) + '\n' + MARK + '\n\n' + prose)
    return dest


if __name__ == '__main__':
    print(build())
