"""Writes the numbers of stale/RESULT_missing.md from the missing points pilot's outputs (stale/PREREG_missing.md):
missing_measures.json (measures 1, 2 and the cards), missing_result.json (measure 3 and the readings), missing_gpt.json
(GPT as the second rater, reported, not read; optional) and the Kev and reranker timings (measure 4).

Everything above the marker line is regenerated; anything below it (the prose, written by hand) is kept.
Usage  py -m stale.missing_report
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); OUT = os.path.join(HERE, 'out')
sys.path.insert(0, ROOT)
from stale.missing import ARMS, DOCS

MARK = '<!-- prose below this line is written by hand and kept when the numbers are regenerated -->'
KEV_PIECE, KEV_Q, INSTRUCT_Q = 7.38, 0.931, 6.33  # bench/RESULT_cost_curve.md (idle CPU)
NAME = {'KEV': 'KEV', 'RERANK': 'RERANK', 'BM25': 'BM25'}


def load(name, out):
    p = os.path.join(out, name)
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else None


def ci(x): return f'{x["point"]:+.3f} [{x["ci95"][0]:+.3f}, {x["ci95"][1]:+.3f}], **{x["reading"]}**'


def pct(a): lo, hi = a['wilson95']; return f'{a["yes"]}/{a["cards"]} = **{a["yes_share"]:.3f}** [{lo:.3f}, {hi:.3f}]'


def build(out=OUT, dest=None, docs=DOCS):
    dest = dest or os.path.join(HERE, 'RESULT_missing.md')
    M, R, G = load('missing_measures.json', out), load('missing_result.json', out), load('missing_gpt.json', out)
    kt = (load('missing_kev.json', out) or {}).get('_timing', {}); rt = (load('missing_rerank.json', out) or {}).get('_timing', {})
    D = {d['doc']: d for d in json.load(open(docs, encoding='utf-8'))['docs']}
    L = ['# Result: missing points pilot (which cases does a document state that ToS;DR has no point for?)', '',
         'GENERATED by `py -m stale.missing_report` from `stale/out/missing_measures.json`, `missing_result.json`, '
         '`missing_gpt.json` and the timings in `missing_kev.json` / `missing_rerank.json`; the prose below the marker is '
         'written by hand. Pre-registration: `stale/PREREG_missing.md` (hashes in `stale/PREREG_missing.sha256`).', '']
    if R:
        L += ['## Readings (fixed in advance)',
              f'- **Pilot: {R["reading"]}.** Kev\'s precision@10 {R["precision_at_10"]["KEV"]["yes_share"]:.3f} (needs at '
              f'least .30), Wilson lower bound {R["precision_at_10"]["KEV"]["wilson95"][0]:.3f} (needs at least .15); '
              f'measure 1 KEV - BM25: {R["measures"]["KEV_minus_BM25_auroc"]["reading"]} (needs KEV better).',
              f'- **Method to build on: {R["method"]}.** Measure 1 KEV - RERANK: '
              f'{R["measures"]["KEV_minus_RERANK_auroc"]["reading"]}; precision@10 KEV '
              f'{R["precision_at_10"]["KEV"]["yes_share"]:.3f} vs RERANK {R["precision_at_10"]["RERANK"]["yes_share"]:.3f}.',
              f'- Validity: {R["random_yes"]} of {R["random_n"]} random control cards rated YES (at most 2 allowed): '
              f'{"valid" if R["valid"] else "NOT VALID"}.', '']
    if M:
        L += ['## Measure 1 (primary): known positives against negatives, AUROC by case score', '',
              '| Document | positives | negatives | KEV | RERANK | BM25 |', '|---|---|---|---|---|---|']
        for r in M['docs']:
            L.append(f'| {r["doc"][:-3]} | {r["positives"]} | {r["negatives"]} | ' + ' | '.join(f'{r[a + "_auroc"]:.3f}' for a in ARMS) + ' |')
        L += ['| **Mean of the four** | | | ' + ' | '.join(f'**{M["auroc"][a]:.3f}**' for a in ARMS) + ' |', '',
              f'- KEV - RERANK: {ci(M["KEV_minus_RERANK_auroc"])}.',
              f'- KEV - BM25: {ci(M["KEV_minus_BM25_auroc"])}.',
              '- 95% intervals from 2,000 draws resampling positives and negatives within each document (seed 20261121).', '',
              '## Measure 2 (descriptive): recall@20, share of known positives in the top 20 of the asked cases', '',
              '| Document | KEV | RERANK | BM25 |', '|---|---|---|---|']
        for r in M['docs']:
            L.append(f'| {r["doc"][:-3]} | ' + ' | '.join(f'{r[a + "_recall20"]:.3f}' for a in ARMS) + ' |')
        L += ['| **Mean** | ' + ' | '.join(f'**{M["recall_at_20"][a]:.3f}**' for a in ARMS) + ' |', '']
    if R:
        c = M['cards'] if M else {}
        L += ['## Measure 3: new suggestions, rated blind (one Claude Opus subagent; case and passage only)', '',
              f'{c.get("total", "?")} cards: each arm\'s top 10 negatives per document with its best passage, deduplicated, '
              f'plus {c.get("random", "?")} random controls. A negative is a case with no approved point on the service.', '',
              '| | KEV | RERANK | BM25 |', '|---|---|---|---|',
              '| Precision@10: rated YES [Wilson 95%] | ' + ' | '.join(pct(R['precision_at_10'][a]) for a in ARMS) + ' |',
              '| YES or PARTLY | ' + ' | '.join(f'{R["precision_at_10"][a]["yes_or_partly_share"]:.3f}' for a in ARMS) + ' |', '']
    if G:
        g, cl, a = G['gpt']['precision_at_10'], G['claude']['precision_at_10'], G['agreement']
        L += ['### The same cards rated by GPT (second rater; reported, not read)', '',
              '| | KEV | RERANK | BM25 | random controls YES |', '|---|---|---|---|---|',
              '| Claude (the rater the readings use) | ' + ' | '.join(pct(cl[x]) for x in ARMS) + f' | {G["claude"]["random_yes"]}/{G["random_n"]} |',
              '| GPT | ' + ' | '.join(pct(g[x]) for x in ARMS) + f' | {G["gpt"]["random_yes"]}/{G["random_n"]} |',
              '| Both rated YES | ' + ' | '.join(f'{a["both_yes_by_arm"][x]}/{cl[x]["cards"]}' for x in ARMS) + ' | |', '',
              f'Card-level agreement on YES vs not YES: {a["agree"]} of {a["cards"]} cards, kappa {a["kappa"]:.3f} '
              f'(Claude YES {a["claude_yes"]}, GPT YES {a["gpt_yes"]}).', '']
    if kt:
        L += ['## Measure 4: cost', '',
              'Kev-4B Q8, one request per passage with all of the document\'s questions not already cached (no other model '
              'job on the CPU; light editing, git commands and tests of mine ran at times). Predicted from the cost benchmark: 7.38 s per passage + 0.931 s per question. The instruct model\'s '
              'cost for the same cells is the benchmark\'s 6.33 s per passage-question (it is not run).', '',
              '| Document | passages | questions | cells asked (cached) | Kev s | Kev s per passage | predicted | instruct s (est.) | instruct / Kev | reranker s |',
              '|---|---|---|---|---|---|---|---|---|---|']
        T = {'p': 0, 'a': 0, 'c': 0, 's': 0.0, 'r': 0.0}
        for doc, t in kt.items():
            p, q, a, cc, s = t['pieces'], t['questions'], t['asked_cells'], t['cached_cells'], t['seconds']
            pred = p * KEV_PIECE + a * KEV_Q; ins = a * INSTRUCT_Q; rr = rt.get(doc)
            T['p'] += p; T['a'] += a; T['c'] += cc; T['s'] += s; T['r'] += rr or 0
            L.append(f'| {doc[:-3]} | {p} | {q} | {a:,} ({cc}) | {s:,.0f} | {s / p:.1f} | {pred / p:.1f} | {ins:,.0f} | {ins / s:.1f}x | '
                     f'{"" if rr is None else f"{rr:,.0f}"} |')
        pred = T['p'] * KEV_PIECE + T['a'] * KEV_Q; ins = T['a'] * INSTRUCT_Q
        L += [f'| **All four** | {T["p"]} | | {T["a"]:,} ({T["c"]:,}) | **{T["s"]:,.0f}** ({T["s"] / 3600:.2f} h) | {T["s"] / T["p"]:.1f} | '
              f'{pred / T["p"]:.1f} | **{ins:,.0f}** ({ins / 3600:.1f} h) | **{ins / T["s"]:.1f}x** | '
              f'{T["r"]:,.0f}{" (" + format(T["r"] / 3600, ".2f") + " h)" if rt else ""} |', '',
              f'Kev per asked cell: {T["s"] / T["a"]:.2f} s; instruct model: {INSTRUCT_Q} s. Kev took {T["s"] / pred:.2f}x the '
              f'benchmark\'s prediction for these calls.', '']
    if R or M:
        p = R['precision_at_10'] if R else {}
        L += ['## Predictions (from the pre-registration) against the result', '', '| | predicted | result |', '|---|---|---|']
        if M:
            L += [f'| AUROC KEV / RERANK / BM25 | .85-.92 / .80-.88 / .70-.80 | {M["auroc"]["KEV"]:.3f} / {M["auroc"]["RERANK"]:.3f} / {M["auroc"]["BM25"]:.3f} |',
                  f'| KEV - RERANK (AUROC) | about +.03, no difference shown | {M["KEV_minus_RERANK_auroc"]["point"]:+.3f}, {M["KEV_minus_RERANK_auroc"]["reading"]} |']
        if R:
            L += [f'| Precision@10 KEV / RERANK / BM25 | .30-.50 / .25-.40 / .15-.30 | {p["KEV"]["yes_share"]:.3f} / {p["RERANK"]["yes_share"]:.3f} / {p["BM25"]["yes_share"]:.3f} |',
                  f'| Worth building | P = 55% | {R["reading"]} |']
        L.append('')
    prose = ''
    if os.path.exists(dest):
        old = open(dest, encoding='utf-8').read()
        if MARK in old: prose = old.split(MARK, 1)[1].lstrip('\n')
    with open(dest, 'w', encoding='utf-8', newline='\n') as f: f.write('\n'.join(L) + '\n' + MARK + '\n\n' + prose)
    print(dest, len(L), 'lines generated;', 'prose kept' if prose else 'no prose yet')


if __name__ == '__main__':
    build()
