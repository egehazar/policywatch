"""Writes the numbers of stale/RESULT_missing_wide.md from the remaining-documents run (stale/PLAN_missing_wide.md):
missing_wide_docs.json (the documents and their cases), missing_wide_measures.json (the one accuracy check fixed in
advance, and the timings) and missing_wide_kev.json (Kev's scores, for the per-document counts).

Everything above the marker line is regenerated; anything below it (the prose, written by hand) is kept.
Usage  py -m stale.missing_wide_report
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); OUT = os.path.join(HERE, 'out')
sys.path.insert(0, ROOT)
from stale.missing_report import MARK, load, ci

PRED = {'CASCADE_KEV': (.66, .76), 'RERANK': (.58, .68), 'diff': (.02, .10)}   # stale/PLAN_missing_wide.md
KEV_ASKED_S = 1.11      # Kev's seconds per asked cell on every passage in the larger test (stale/RESULT_missing2.md)


def band(x, lo, hi): return 'inside' if lo <= x <= hi else ('above' if x > hi else 'below')


def build(out=OUT, dest=None):
    dest = dest or os.path.join(HERE, 'RESULT_missing_wide.md')
    D = (load('missing_wide_docs.json', out) or {}).get('docs', []); M = load('missing_wide_measures.json', out)
    L = ['# Result: missing points on the remaining 20 documents (a build, with one accuracy check)', '',
         'GENERATED by `py -m stale.missing_wide_report` from `stale/out/missing_wide_docs.json` and '
         '`missing_wide_measures.json`; the prose below the marker is written by hand. Plan: `stale/PLAN_missing_wide.md` '
         '(hashes in `stale/PLAN_missing_wide.sha256`). No suggestion from this run was rated by anyone.', '']
    if M:
        a, d = M['auroc'], M['CASCADE_KEV_minus_RERANK_auroc']
        L += ['## The accuracy check (fixed in advance)',
              f'On the {len(M["docs"])} documents with at least 10 known positives (cases whose approved ToS;DR quote is still '
              'found in the current text of the document): how well each arm ranks those cases above the frequent cases the '
              'service has no approved point for (AUROC, mean over the documents).', '',
              f'- CASCADE_KEV - RERANK: {ci(d)}.',
              f'- CASCADE_KEV (Kev on the reranker\'s top 3 passages per case) **{a["CASCADE_KEV"]:.3f}**, predicted .66-.76: '
              f'{band(a["CASCADE_KEV"], *PRED["CASCADE_KEV"])} the range.',
              f'- RERANK (every passage) **{a["RERANK"]:.3f}**, predicted .58-.68: {band(a["RERANK"], *PRED["RERANK"])} the range.',
              f'- Difference {d["point"]:+.3f}, predicted +.02 to +.10: {band(d["point"], *PRED["diff"])} the range '
              '(P(CASCADE_KEV better) was put at 50%).', '',
              '| Document | Known positives | No point on the service | CASCADE_KEV | RERANK |', '|---|---:|---:|---:|---:|']
        for r in M['docs']:
            L.append(f'| {r["doc"][:-3]} | {r["positives"]} | {r["negatives"]} | {r["CASCADE_KEV_auroc"]:.3f} | {r["RERANK_auroc"]:.3f} |')
        L.append('')
    if D:
        P = sum(len(x['pieces']) for x in D); N = sum(len(x['negatives']) for x in D)
        cells = sum(len(x['pieces']) * len(x['cases']) for x in D)
        L += ['## What the run built',
              f'- {len(D)} documents ({sum(x["type"] == "privacy" for x in D)} privacy policies, '
              f'{sum(x["type"] != "privacy" for x in D)} terms), {P:,} passages, {cells:,} passage-case cells.',
              f'- {N:,} document-case pairs ({len({c for x in D for c in x["negatives"]})} distinct cases) the service has no '
              f'approved point for (any quote length, from `stale/data/<platform>.json`); {sum(len(x["excluded"]) for x in D):,} '
              f'pairs ({len({c for x in D for c in x["excluded"]})} distinct cases) excluded because it has one.',
              f'- The private curator page lists each document\'s top 10 of those cases by Kev\'s score on its best '
              f'shortlisted passage: {sum(min(10, len(x["negatives"])) for x in D)} suggestions, marked "not rated".', '']
    if M and M.get('timing', {}).get('KEV'):
        K, R = M['timing']['KEV'], M['timing']['RERANK'] or {}
        ks = sum(t['seconds'] for t in K.values()); asked = sum(t['asked_cells'] for t in K.values())
        cached = sum(t['cached_cells'] for t in K.values()); sc = sum(t['cells'] for t in K.values())
        rs = sum(R.values()); cells = sum(len(x['pieces']) * len(x['cases']) for x in D)
        L += ['## Cost (measured on this machine, 6 cores)',
              f'- Reranker on every cell: {rs:,.0f} s ({rs / 3600:.1f} h), {rs / cells:.2f} s per cell.',
              f'- Kev on the shortlist: {sc:,} cells ({asked:,} asked, {cached:,} from the cache), {ks:,.0f} s '
              f'({ks / 3600:.1f} h), {ks / max(asked, 1):.2f} s per asked cell (one request per passage, about '
              f'{sc / max(sum(t["pieces"] for t in K.values()), 1):.1f} questions each).',
              f'- Kev on every cell would have been about {cells * KEV_ASKED_S / 3600:.0f} h at the larger test\'s '
              f'{KEV_ASKED_S} s per asked cell (estimated, not run); the cascade took {(rs + ks) / 3600:.1f} h in all.', '']
    prose = ''
    if os.path.exists(dest):
        old = open(dest, encoding='utf-8').read()
        if MARK in old: prose = old.split(MARK, 1)[1].lstrip('\n')
    with open(dest, 'w', encoding='utf-8', newline='\n') as f: f.write('\n'.join(L) + '\n' + MARK + '\n\n' + prose)
    return dest


if __name__ == '__main__':
    print(build())
