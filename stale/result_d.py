"""Writes stale/RESULT_relocate_d.md from part D's result files (stale/out/contrib_result.json, contrib_margin.json,
contrib_docs.json): tables, readings, the addendum-1 label rule and the predictions, with no interpretation beyond
the pre-registered rules. Prose is added by hand afterwards.
Usage  py -m stale.result_d
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); OUT = os.path.join(HERE, 'out')

PRED = {'KEV': .65, 'CASCADE_RERANK': .64, 'RERANK': .58, 'BM25': .40, 'BGE': .38}


def f3(x): return '' if x is None else f'{x:.3f}'.replace('0.', '.', 1) if x >= 0 else f'-{-x:.3f}'.replace('0.', '.', 1)


def iv(b): return f"{'+' if b['point'] >= 0 else ''}{f3(b['point'])} [{f3(b['ci95'][0])}, {f3(b['ci95'][1])}]"


def main():
    R = json.load(open(os.path.join(OUT, 'contrib_result.json'), encoding='utf-8'))['result']
    M = json.load(open(os.path.join(OUT, 'contrib_margin.json'), encoding='utf-8')) if os.path.exists(os.path.join(OUT, 'contrib_margin.json')) else {}
    D = json.load(open(os.path.join(OUT, 'contrib_docs.json'), encoding='utf-8'))
    rd = R['reading']; h = R['hit_at']; mrr = R['mrr']
    arms = sorted([a for a in h if a != 'RANDOM'], key=lambda a: -h[a]['1']) + ['RANDOM']
    L = ['# Part D: relocation on Open Terms Archive\'s contrib text, and the reranker-first cascade: result', '',
         'GENERATED by `py -m stale.result_d` from the hashed result files; the prose is added by hand afterwards.', '',
         'Pre-registration: `stale/PREREG_relocate_d.md` and `stale/PREREG_relocate_d_addendum1.md` (hashes, the draw and the',
         'result in `stale/PREREG_relocate_d.sha256`).', '',
         f"**Population.** {R['points']} points from {R['services']} ToS;DR services in {R['documents']} documents of the contrib "
         f"collection at {D['archive_head'][:10]}; {R['cost']['cells']:,} piece-question cells.", '',
         '## Readings', '| Reading | Difference, 95% interval over services | Result |', '|---|---|---|',
         f"| D0: KEV - BM25 | {iv(R['KEV_minus_BM25'])} | {rd['D0_replication']} (both intervals above 0 needed) |",
         f"| D0: KEV - BGE | {iv(R['KEV_minus_BGE'])} | |",
         f"| D1: CASCADE_RERANK - KEV (bar: lower bound at least -.03) | {iv(R['CASCADE_RERANK_minus_KEV'])} | {rd['D1_cascade']} |",
         f"| D2: KEV - RERANK | {iv(R['KEV_minus_RERANK'])} | {rd['D2_reranker']} |", '',
         '## Arms', '| Arm | hit@1 | hit@3 | hit@5 | MRR |', '|---|---|---|---|---|']
    L += [f"| {a} | {f3(h[a]['1'])} | {f3(h[a]['3'])} | {f3(h[a]['5'])} | {f3(mrr.get(a))} |" for a in arms]
    c = R['cost']
    L += ['', '## Cost', f"- KEV {c['KEV_sec_per_cell']} s per cell, RERANK {c['RERANK_sec_per_cell']} s per cell (sharing the CPU with "
          'the deferred steps of `run_resume.sh`, as the pre-registration allows).',
          f"- The cascade asks Kev {c['cascade_kev_cells']:,} of {c['cells']:,} cells ({c['cascade_kev_share']:.0%}).", '']
    if 'D' in M:
        d = M['D']
        L += ['## Addendum 1: the "clear" label', f"- {d['clear']} of {d['points']} points clear (margin at least .30, {d['clear_share']:.0%}): "
              f"hit@1 {f3(d['clear_hit1'])} [{', '.join(f3(x) for x in d.get('clear_hit1_ci95') or [])}]; the rest {f3(d['rest_hit1'])} (hit@3 {f3(d['rest_hit3'])}).",
              f"- Rule: at least 30 clear, hit@1 at least .85, lower bound at least .75. **{d['reading']}**.",
              f"- Parts A and B (exploratory, where the cut was chosen): {f3(M['A_exploratory']['clear_hit1'])} and {f3(M['B_exploratory']['clear_hit1'])}.", '']
    L += ['## Prediction against result', '| | predicted | result |', '|---|---|---|']
    L += [f'| hit@1 {a} | {f3(p)} | {f3(h[a]["1"])} |' for a, p in PRED.items()]
    L += [f"| P(D0 REPLICATED) | 85% | {rd['D0_replication'].lower()} |", f"| P(D1 CASCADE ADOPTED) | 75% | {rd['D1_cascade'].lower()} |",
          f"| P(D2 = decision model better than the reranker) | 35% | {rd['D2_reranker'].lower()} |"]
    if 'D' in M: L += [f"| P(label adopted), clear share, clear hit@1 | 65%, 30%, .88 | {M['D']['reading'].lower()}, {M['D']['clear_share']:.0%}, {f3(M['D']['clear_hit1'])} |"]
    with open(os.path.join(HERE, 'RESULT_relocate_d.md'), 'w', encoding='utf-8') as fh: fh.write('\n'.join(L) + '\n')
    print(os.path.join(HERE, 'RESULT_relocate_d.md'))


if __name__ == '__main__':
    main()
