"""Writes the numbers of stale/RESULT_wide_rate.md from the blind rating of the page's 28 unrated documents
(stale/PLAN_wide_rate.md): wide_rate_result.json (the Claude raters' verdicts, scored by `py -m stale.wide_rate score`)
and, if it exists, wide_rate_gpt.json (GPT as the second rater, reported, never read).

Everything above the marker line is regenerated; anything below it (the prose, written by hand) is kept.
Usage  py -m stale.wide_rate_report
"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE); OUT = os.path.join(HERE, 'out')
sys.path.insert(0, ROOT)
from stale.missing_report import MARK, load, pct

RUN = {'missing_wide': 'the 20 of the remaining-documents run', 'missing_rest': 'the last 6 (no matched point)',
       'missing_watch': "Pinterest's 2, on their new text"}


def d3(x): return f'{x["point"]:+.3f} [{x["ci95"][0]:+.3f}, {x["ci95"][1]:+.3f}]'


def build(out=OUT, dest=None):
    dest = dest or os.path.join(HERE, 'RESULT_wide_rate.md')
    R = load('wide_rate_result.json', out); G = load('wide_rate_gpt.json', out)
    L = ['# Result: the page\'s unrated suggestions, rated blind', '',
         'GENERATED by `py -m stale.wide_rate_report` from `stale/out/wide_rate_result.json` (and `wide_rate_gpt.json`); '
         'the prose below the marker is written by hand. Plan: `stale/PLAN_wide_rate.md` (hashes in '
         '`stale/PLAN_wide_rate.sha256`). The raters are AI models, not people.', '']
    if R:
        p, r = R['precision_at_10']['PAGE'], R['precision_at_10']['RERANK']
        L += ['## Readings (fixed in advance)',
              f'- Validity: {R["random_yes"]} of {R["random_n"]} random controls rated YES (at most 3 allowed): '
              f'{"valid" if R["valid"] else "NOT VALID"}.',
              f'- Page precision: {pct(p)}, predicted .55-.75: **{R["reading_page"]}**.',
              f'- PAGE - RERANK: {d3(R["PAGE_minus_RERANK"])} over {R["PAGE_minus_RERANK"]["documents"]} documents, '
              f'**{R["reading_compare"]}** (predicted +.10 to +.30; P(PAGE better) was put at 75%).', '',
              '| | PAGE (Kev on the shortlist) | RERANK (every passage) |', '|---|---|---|',
              f'| Rated YES [Wilson 95%] | {pct(p)} | {pct(r)} |',
              f'| YES or PARTLY | {p["yes_or_partly_share"]:.3f} | {r["yes_or_partly_share"]:.3f} |', '',
              '## Descriptive (nothing is read from these)', '',
              '| Subset | PAGE YES | RERANK YES |', '|---|---|---|']
        for k, name in RUN.items():
            b = R['by_run'][k]; L.append(f'| {name} | {pct(b["PAGE"])} | {pct(b["RERANK"])} |')
        e = R['english_only']
        L += [f'| English documents only | {pct(e["PAGE"])} | {pct(e["RERANK"])} |',
              f'| Ranks 1-5 | {pct(R["by_rank"]["PAGE"]["1-5"])} | {pct(R["by_rank"]["RERANK"]["1-5"])} |',
              f'| Ranks 6-10 | {pct(R["by_rank"]["PAGE"]["6-10"])} | {pct(R["by_rank"]["RERANK"]["6-10"])} |']
        for x in sorted(R['by_folder']):
            b = R['by_folder'][x]; L.append(f'| Rater {x.upper()} (folder {x}) | {pct(b["PAGE"])} | {pct(b["RERANK"])} |')
        L += ['', f'- English documents only, PAGE - RERANK: {d3(e["PAGE_minus_RERANK"])}.',
              f'- Verdicts on all {sum(R["verdict_counts"].values())} cards: ' +
              ', '.join(f'{k} {R["verdict_counts"].get(k, 0)}' for k in ('YES', 'PARTLY', 'NO')) + '.', '',
              '| Document | PAGE YES | RERANK YES |', '|---|---:|---:|']
        for doc, b in R['by_doc'].items():
            L.append(f'| {doc[:-3]} | {b["PAGE"]["yes"]}/{b["PAGE"]["cards"]} | {b["RERANK"]["yes"]}/{b["RERANK"]["cards"]} |')
        L.append('')
    if G:
        g, c, a = G['gpt'], G['claude'], G['agreement']
        L += ['## Second rater: GPT (reported, never read)',
              f'- GPT: PAGE {pct(g["precision_at_10"]["PAGE"])}, RERANK {pct(g["precision_at_10"]["RERANK"])}; '
              f'PAGE - RERANK {d3(g["PAGE_minus_RERANK"])}; random controls rated YES {g["random_yes"]} of {G["random_n"]}.',
              f'- Agreement with the Claude raters on YES against not YES: {a["agree_yes_vs_not"]} of {a["cards"]} cards, '
              f'kappa {a["kappa_yes_vs_not"]:.3f}; same verdict of three on {a["agree_three_way"]}. Both rated YES: '
              f'{a["both_yes_by_arm"]["PAGE"]} PAGE cards, {a["both_yes_by_arm"]["RERANK"]} RERANK cards.', '']
    prose = ''
    if os.path.exists(dest):
        old = open(dest, encoding='utf-8').read()
        if MARK in old: prose = old.split(MARK, 1)[1].lstrip('\n')
    with open(dest, 'w', encoding='utf-8', newline='\n') as f: f.write('\n'.join(L) + '\n' + MARK + '\n\n' + prose)
    return dest


if __name__ == '__main__':
    print(build())
